// Regenerates src/data/nl-map.ts (province outlines as SVG paths) from a province GeoJSON.
// Usage: node scripts/build-nl-map.mjs <provincies.geojson>
// Source used: https://cartomap.github.io/nl/wgs84/provincie_2023.geojson  (PDOK / CBS open data,
// Dutch province boundaries 2023, WGS84 lon/lat).
import { readFileSync, writeFileSync } from "node:fs";

const input = process.argv[2];
if (!input) throw new Error("usage: node scripts/build-nl-map.mjs <provincies.geojson>");
const geo = JSON.parse(readFileSync(input, "utf8"));

const SCALE = 120; // SVG units per degree of latitude
const LAT0 = 52.2; // latitude used to squash longitude (equirectangular, good enough for one small country)
const kx = Math.cos((LAT0 * Math.PI) / 180);

let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
const project = ([lon, lat]) => [lon * kx * SCALE, -lat * SCALE];
const polysOf = (g) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates);

for (const f of geo.features)
  for (const poly of polysOf(f.geometry))
    for (const ring of poly)
      for (const p of ring) {
        const [x, y] = project(p);
        minX = Math.min(minX, x); maxX = Math.max(maxX, x);
        minY = Math.min(minY, y); maxY = Math.max(maxY, y);
      }

const PAD = 6;
const ox = minX - PAD, oy = minY - PAD;
const fix = (n) => (Math.round(n * 10) / 10).toString();
const to = (p) => { const [x, y] = project(p); return [x - ox, y - oy]; };

const provinces = geo.features.map((f) => {
  const d = polysOf(f.geometry)
    .flatMap((poly) => poly)
    .map((ring) => "M" + ring.map(to).map(([x, y]) => `${fix(x)} ${fix(y)}`).join("L") + "Z")
    .join("");
  return { name: f.properties.statnaam, d };
});

const [hx, hy] = to([4.3007, 52.0705]); // Den Haag (The Hague)
const out = `// GENERATED by scripts/build-nl-map.mjs - do not edit by hand.
// Dutch province outlines (PDOK / CBS open data, 2023) projected to SVG units.
export const NL_VIEWBOX = { width: ${fix(maxX - minX + 2 * PAD)}, height: ${fix(maxY - minY + 2 * PAD)} };
export const DEN_HAAG = { x: ${fix(hx)}, y: ${fix(hy)} };
export const NL_PROVINCES: { name: string; d: string }[] = ${JSON.stringify(provinces, null, 2)};
`;
writeFileSync(new URL("../src/data/nl-map.ts", import.meta.url), out);
console.log("provinces:", provinces.length, "viewBox:", fix(maxX - minX + 2 * PAD), "x", fix(maxY - minY + 2 * PAD), "den haag:", fix(hx), fix(hy));
