// URL parity check: every URL of the live Hugo site must exist in dist/ or be covered by a redirect rule.
//   node scripts/seo-url-diff.mjs [--live https://www.ppmedenhaag.nl] [--write]      (needs network + a built dist/)
// --write stores the report in docs/seo/url-diff.md. Exit code 1 when live URLs are neither served nor redirected.
import { existsSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : fallback;
};
const LIVE = arg("--live", "https://www.ppmedenhaag.nl").replace(/\/+$/, "");
const DIST = resolve("dist");
const write = process.argv.includes("--write");

async function locs(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url} -> ${res.status}`);
  return [...(await res.text()).matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1]);
}

const live = new Set();
for (const l of ["nl", "id", "en"]) for (const u of await locs(`${LIVE}/${l}/sitemap.xml`)) live.add(new URL(u).pathname);

const served = (p) => {
  const f = join(DIST, decodeURIComponent(p));
  return existsSync(f) && (statSync(f).isFile() || existsSync(join(f, "index.html")));
};
const rules = readFileSync("public/_redirects", "utf8")
  .split("\n")
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith("#"))
  .map((l) => {
    const [from, to, status] = l.split(/\s+/);
    return { from, to, status };
  });
const redirectFor = (p) =>
  rules.find((r) => (r.from.endsWith("*") ? p.startsWith(r.from.slice(0, -1)) : p === r.from || p === `${r.from}/`));

const ok = [];
const redirected = [];
const missing = [];
for (const p of [...live].sort()) {
  if (served(p)) ok.push(p);
  else {
    const r = redirectFor(p);
    if (r) redirected.push([p, r.to, r.status]);
    else missing.push(p);
  }
}

const feeds = ["", "event", "blog", "dakwah", "ibadah", "about"].flatMap((s) =>
  ["", "id", "en"].map((l) => `/${[l, s].filter(Boolean).join("/")}/index.xml`.replace("//", "/")),
);
const liveFeeds = [];
for (const f of feeds) {
  const r = await fetch(LIVE + f, { method: "HEAD" });
  if (r.ok) liveFeeds.push(f);
}
const missingFeeds = liveFeeds.filter((f) => !existsSync(join(DIST, f)));

const lines = [
  `# URL parity: live Hugo site vs this build`,
  ``,
  `Generated by \`npm run seo:diff -- --write\` on ${new Date().toISOString().slice(0, 10)} against ${LIVE}.`,
  ``,
  `| | count |`,
  `|---|---|`,
  `| live URLs (sitemaps) | ${live.size} |`,
  `| served 1:1 | ${ok.length} |`,
  `| 301 redirect rule | ${redirected.length} |`,
  `| **missing (404)** | **${missing.length}** |`,
  `| live feeds not served | ${missingFeeds.length} of ${liveFeeds.length} |`,
  ``,
  missing.length ? `## Missing\n${missing.map((p) => `- ${p}`).join("\n")}\n` : `No missing URLs.\n`,
  redirected.length
    ? `## Redirected (public/_redirects)\n${redirected.map(([p, to, s]) => `- ${p} → ${to} (${s})`).join("\n")}\n`
    : "",
  missingFeeds.length ? `## Feeds missing\n${missingFeeds.map((f) => `- ${f}`).join("\n")}\n` : "",
];
const report = lines.join("\n");
console.log(report.split("\n").slice(0, 14).join("\n"));
if (missing.length) console.log(`\nMissing:\n${missing.slice(0, 30).join("\n")}`);
if (write) writeFileSync("docs/seo/url-diff.md", report);
process.exit(missing.length || missingFeeds.length ? 1 : 0);
